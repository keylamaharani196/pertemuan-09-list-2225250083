
# Input: Menyimpan enam nilai ke dalam list.
nilai = [75, 80, 65, 90, 88, 70]

# Proses: Mengakses elemen menggunakan indeks dan slicing.
# Output: Menampilkan elemen pertama, terakhir,
# tiga elemen awal, dan elemen indeks 1 sampai 3.
print(nilai[0])
print(nilai[-1])
print(nilai[:3])
print(nilai[1:4])
